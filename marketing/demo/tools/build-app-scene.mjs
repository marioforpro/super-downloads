// Builds compositions/app.html from src/app.tpl.html + the real app UI
// extracted by tools/extract-ui.cjs (assets/app/app.css + parts.json).
//   {{CSS}}               the app's scoped CSS
//   {{PART:key}}          a state's HTML (ids stripped)
//   {{ROW:key:prefix}}    a row's HTML; its progress fill / percent get ids prefix-fill / prefix-pct
// Run: node marketing/demo/tools/build-app-scene.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const css = fs.readFileSync(path.join(DIR, "assets/app/app.css"), "utf8");
const parts = JSON.parse(fs.readFileSync(path.join(DIR, "assets/app/parts.json"), "utf8"));

const stripIds = (html) => html.replace(/\s(id|title|aria-[a-z]+)="[^"]*"/g, "");
const tagRow = (html, prefix) =>
  stripIds(html)
    .replace('class="progress-bar-fill', `id="${prefix}-fill" class="progress-bar-fill`)
    .replace('class="download-item-percent', `id="${prefix}-pct" class="download-item-percent`);

// Two layouts from one template: the 16:9 master and the 9:16 recomposition.
const S_L = 2.3, S_V = 2.08;
const LAYOUTS = {
  "compositions/app.html": {
    id: "app", W: 1920, H: 1080, S: S_L, winX: 720, winY: 110, winW: Math.round(480 * S_L), winH: Math.round(387 * S_L),
    glowX: 760, glowY: 170, glowW: 1024, glowH: 760, camOX: 1272, camOY: 562,
    leftX: 110, titleW: 560, titleY: 330, titleSize: 92, keyY: 640, keysX: 0, keys2X: 128,
    capX: 960, capY: 340, capScale: 1.12, punchS: 1.5, punchX: 270, punchY: 219, punchS2: 1.53, punchX2: 276, punchY2: 225,
    curX: 1560, curY: 1140, dragX: 560, dragY: 820, leave: -520,
  },
  "compositions/v-app.html": {
    id: "v-app", W: 1080, H: 1920, S: S_V, winX: 41, winY: 540, winW: Math.round(480 * S_V), winH: Math.round(387 * S_V),
    glowX: 81, glowY: 600, glowW: 918, glowH: 700, camOX: 540, camOY: 840,
    leftX: 70, titleW: 940, titleY: 236, titleSize: 120, keyY: 262, keysX: 640, keys2X: 768,
    capX: 540, capY: 640, capScale: 1.0, punchS: 1.45, punchX: 200, punchY: 110, punchS2: 1.48, punchX2: 204, punchY2: 114,
    curX: 1000, curY: 1900, dragX: 300, dragY: 1240, leave: -900,
  },
};

let tpl = fs.readFileSync(path.join(DIR, "src/app.tpl.html"), "utf8");
for (const [file, L] of Object.entries(LAYOUTS)) {
let out = tpl.replace(/\{\{L:(\w+)\}\}/g, (_, k) => {
  if (!(k in L)) throw new Error(`layout ${file} missing ${k}`);
  return String(L[k]);
});
// The film drives every state: drop CSS transitions (browser clock) and system mono faces the renderer can't load.
const appCss = css
  .replace(/^\/\*.*\*\/\n/, "")
  .replace(/transition:[^;}]*;?/g, "")
  .replace(/ui-monospace,\s*SFMono-Regular,\s*Menlo,\s*monospace/g, "monospace");
out = out.replace("{{CSS}}", appCss);
out = out.replace(/\{\{ROW:([\w-]+):([\w-]+)\}\}/g, (_, key, prefix) => {
  if (!parts[key]) throw new Error(`missing part ${key}`);
  return tagRow(parts[key], prefix);
});
out = out.replace(/\{\{PART:([\w-]+)\}\}/g, (_, key) => {
  if (!parts[key]) throw new Error(`missing part ${key}`);
  let html = stripIds(parts[key]);
  if (key === "topReady") html = html.replace('<input type="text"', '<input type="text" value="https://www.youtube.com/watch?v=WhWc3b3KhnY"');
  return html;
});
out = out.replace("<template>", "<template>\n  <!-- Generated by tools/build-app-scene.mjs from src/app.tpl.html — edit the template -->");
fs.writeFileSync(path.join(DIR, file), out);
console.log("wrote", file, out.length, "bytes");
}
